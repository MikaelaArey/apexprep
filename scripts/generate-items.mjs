#!/usr/bin/env node
// Writes the item-model questions (answers computed or proved in code) to
// content/<exam>/<section>-gen.yaml, plus their concept cards. Run, then build:
//
//   node scripts/generate-items.mjs && npm run content

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dump } from 'js-yaml';
import * as bb from './item-models/bb.mjs';
import * as bbConcepts from './item-models/concepts-bb.mjs';
import * as cpConcepts from './item-models/concepts-cp.mjs';
import * as cp from './item-models/cp.mjs';
import * as lr from './item-models/lsat-logic.mjs';
import * as psConcepts from './item-models/concepts-ps.mjs';
import * as ps from './item-models/ps.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const header = (what) => `# GENERATED by scripts/generate-items.mjs — edit the item models, not this file.\n# ${what}\n\n`;

const kpRows = { lsat: [], mcat: [] };
for (const [exam, section, models, name, what] of [
  ['mcat', 'CP', cp, 'cp-gen', 'calculation questions'],
  ['mcat', 'BB', bb, 'bb-gen', 'calculation questions'],
  ['mcat', 'PS', ps, 'ps-gen', 'calculation questions'],
  ['mcat', 'CP', cpConcepts, 'cp-concepts-gen', 'concept questions (look-alike terms as distractors)'],
  ['mcat', 'BB', bbConcepts, 'bb-concepts-gen', 'concept questions (look-alike terms as distractors)'],
  ['mcat', 'PS', psConcepts, 'ps-concepts-gen', 'concept questions (look-alike terms as distractors)'],
  ['lsat', 'LR', lr, 'lr-gen', 'formal-logic questions, answers proved by a model checker'],
]) {
  const items = [];
  let n = 5001;
  models.build((item) => {
    items.push({ id: `${exam}-${section.toLowerCase()}-${n++}`, model: `${section.toLowerCase()}-${item.type}`, ...item, siblings: [] });
  });
  // Variants built from the same model and concept are natural re-test siblings.
  for (const item of items) {
    item.siblings = items
      .filter((other) => other !== item && other.model === item.model && other.kps[0] === item.kps[0])
      .map((other) => other.id)
      .slice(0, 4);
  }
  const file = join(root, 'content', exam, `${name}.yaml`);
  writeFileSync(file, header(`${items.length} ${section} ${what} from item models.`) + dump(items, { lineWidth: 110, noRefs: true }));
  console.log(`${file.replace(root + '/', '')}: ${items.length} questions`);
  for (const [id, title, front, back] of models.knowledgePoints) kpRows[exam].push({ id, section, title, front, back });
}

for (const [exam, rows] of Object.entries(kpRows)) {
  if (!rows.length) continue;
  const kpFile = join(root, 'content', exam, 'knowledge-points-gen.yaml');
  writeFileSync(kpFile, header('Concept cards for the item-model questions.') + dump(rows, { lineWidth: 110 }));
  console.log(`${kpFile.replace(root + '/', '')}: ${rows.length} concept cards`);
}
