#!/usr/bin/env node
// Writes the MCAT item-model questions (calculations whose answers are computed in
// code) to content/mcat/*-gen.yaml, plus their concept cards. Run, then build:
//
//   node scripts/generate-items.mjs && npm run content

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dump } from 'js-yaml';
import * as bb from './item-models/bb.mjs';
import * as cp from './item-models/cp.mjs';
import * as ps from './item-models/ps.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const header = (what) => `# GENERATED by scripts/generate-items.mjs — edit the item models, not this file.\n# ${what}\n\n`;

const kpRows = [];
for (const [section, models] of [
  ['CP', cp],
  ['BB', bb],
  ['PS', ps],
]) {
  const items = [];
  let n = 5001;
  models.build((item) => {
    items.push({ id: `mcat-${section.toLowerCase()}-${n++}`, model: `${section.toLowerCase()}-${item.type}`, ...item, siblings: [] });
  });
  // Variants built from the same model and concept are natural re-test siblings.
  for (const item of items) {
    item.siblings = items
      .filter((other) => other !== item && other.model === item.model && other.kps[0] === item.kps[0])
      .map((other) => other.id)
      .slice(0, 4);
  }
  const file = join(root, 'content/mcat', `${section.toLowerCase()}-gen.yaml`);
  writeFileSync(file, header(`${items.length} ${section} calculation questions from item models.`) + dump(items, { lineWidth: 110, noRefs: true }));
  console.log(`${file.replace(root + '/', '')}: ${items.length} questions`);
  for (const [id, title, front, back] of models.knowledgePoints) kpRows.push({ id, section, title, front, back });
}

const kpFile = join(root, 'content/mcat/knowledge-points-gen.yaml');
writeFileSync(kpFile, header('Concept cards for the item-model questions.') + dump(kpRows, { lineWidth: 110 }));
console.log(`${kpFile.replace(root + '/', '')}: ${kpRows.length} concept cards`);
